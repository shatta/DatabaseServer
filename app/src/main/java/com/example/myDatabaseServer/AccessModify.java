    private void modifyInfo() {
        try {  
        databaseURL = databaseURLHeader + databaseHostName + ":" + databasePort + "/" + databaseName + secureTransport;
        databaseConn = DriverManager.getConnection(databaseURL,databaseUsername,databasePassword);
        if(databaseConn == null) {
         JOptionPane.showMessageDialog(null,"Unable to connect to Database!");
        } else {
           myPrepStmt = databaseConn.prepareStatement(modifyAccessQuery);
           myPrepStmt.setString(1, newAccessLevel);
           myPrepStmt.setString(2, UserName);
           
           int resultUpdate = myPrepStmt.executeUpdate();
           
           if(resultUpdate > 0) {
               JOptionPane.showMessageDialog(null,"Updated User Access Level");
           } else {
               JOptionPane.showMessageDialog(null,"Unable to Update Access Level!");
           }
        } // End of if-else statement for connecting to database.
      } catch (SQLException e) {
          JOptionPane.showMessageDialog(null,e.getMessage());
      }  
    }


